#!/bin/bash
# Проверка полноты аннотаций: каждый из 1024 слов оверлея должен быть
# представлен в реконструированном МАДЛЕН-тексте.
set -u
cd "$(dirname "$0")/.." || exit 1
rc=0
for f in src/LO_SYN.mad src/LO_GEN.mad; do
    [ -s "$f" ] || { echo "FAIL $f нет"; rc=1; continue; }
    # Строгий формат блока: строка комментария начинается с `С` (возможно,
    # с дефисами), затем «слово NNNN». Встроенные упоминания слов в смысловых
    # комментариях не учитываются.
    n=$(grep -oE '^С[-]*[[:space:]]*(слово|word)[[:space:]]+[0-7]{3,4}' "$f" \
        | awk '{print $NF}' | sort -u | wc -l)
    if [ "$n" -eq 1024 ]; then
        echo "OK $f: $n/1024 слов аннотировано"
    else
        echo "FAIL $f: найдено $n уникальных меток слов, ожидалось 1024" >&2
        rc=1
    fi
done
exit $rc
