#!/usr/bin/env python3
"""67 — zone N+2 comes from our O412C emitter, not from live 4.12 words.

The 375 words at N+2 offsets 526..900 were generated by compiling
src/newcomp/O412C.FTN with SYSTEM FOREX 2.02 (0 ERR, O412CNW 410) and are kept
here as a hex fixture.  They are value-identical to the live 2148:0o1552 table
(the emitter was seeded from it), but at install time nothing is read from the
live overlay: all 375 words come from our own source.

A/B: zeroing emitted word 526 or 900 kills the marker; restoring brings it back.
Reuses tests/plan-f77/66-newcomp-ourcode/run.py:make_case verbatim.
"""
import importlib.util
import os
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
RUN66 = ROOT / 'tests/plan-f77/66-newcomp-ourcode/run.py'
O412B = ROOT / 'src/newcomp/O412B.FTN'
OVL_HEX = ROOT / 'tests/plan-f77/65-m80-install/ovl_our.hex'
EMIT_HEX = HERE / 'o412c_words.hex'
SHARE = Path(os.environ.get('BESM6_DISK_SHARE', '/usr/local/share/besm6'))
START, END = 526, 900


def words_from_hex(path):
    raw = bytes.fromhex(Path(path).read_text().strip())
    return [int.from_bytes(raw[i:i + 6], 'big') for i in range(0, len(raw) - 5, 6)]


def main():
    for f in (RUN66, O412B, OVL_HEX, EMIT_HEX, SHARE / '2048', SHARE / '2148'):
        if not Path(f).exists():
            raise SystemExit(f'FAIL: missing {f}')
    spec = importlib.util.spec_from_file_location('run66', RUN66)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)

    obj = words_from_hex(OVL_HEX)
    emitted = words_from_hex(EMIT_HEX)
    if len(obj) != 1024 or obj[0] != 0o166:
        raise SystemExit('FAIL: unexpected rebuilt SETTRAN object')
    if len(emitted) != 410:
        raise SystemExit(f'FAIL: expected 410 emitted words, got {len(emitted)}')
    o412 = m.parse_o412b()
    live1551 = m.zone_from_disk(SHARE / '2148', 0o1551)

    base = Path(tempfile.mkdtemp(prefix='our-n2-', dir=os.environ.get('TMPDIR', '/tmp')))
    print(f'workspace: {base}')
    print(f'emitted critical words: {START}={emitted[35]:o}, {END}={emitted[409]:o}')

    def z2(zero=()):
        out = [0] * 1024
        for i, w in enumerate(emitted[35:]):
            out[START + i] = 0 if (START + i) in zero else w
        return out

    cases = [('normal', ()), ('zero526', (START,)), ('restore', ()), ('zero900', (END,))]
    res = {}
    for name, zero in cases:
        d, marker = m.make_case(base, name, 'normal', obj, o412, live1551, z2(zero))
        res[name] = marker
        print(f'{name:10s} marker={"YES" if marker else "no":3s}  {d}')

    ok = res['normal'] and res['restore'] and not res['zero526'] and not res['zero900']
    print('VERDICT:', 'PASS' if ok else 'FAIL')
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
